"""One source for the headline numbers quoted in the README, deck, architecture and script.

Reads the machine-readable results and writes results/summary.json, with each value already
formatted (from unrounded values) the way the documents quote it, and rewrites the README's two
result tables between their markers. tests/test_docs_consistency.py checks that the documents
quote these exact strings and that the README tables match, so a rerun that changes a number
makes the tests fail until the documents are updated.

Run from the repository root after evaluate.py and scenario_sensitivity.py:
    python scripts/summarise.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def f1(x):
    return f"{x:.1f}"


def interval(lo_hi, sign=1):
    lo, hi = sorted(sign * v for v in lo_hi)
    return f"{f1(lo)} to {f1(hi)}"


FORECAST_ROWS = [("persistence", "No change (persistence)"), ("trend", "Recent trend extrapolated"),
                 ("physiology", "Physiology core only"), ("A", "Machine learning, dynamic only"),
                 ("B", "Machine learning + clinical record"), ("D", "Machine learning + physiology"),
                 ("C", "Hybrid: ML + clinical record + physiology (primary)")]
ALERT_ROWS = [("current", "Current corrected reading"), ("trend", "Trend forecast, 30 min"),
              ("physiology", "Physiology core forecast, 30 min"), ("ml", "Machine learning forecast, 30 min"),
              ("hybrid", "Hybrid forecast, 30 min"), ("classifier", "Hybrid classifier, low within 60 min")]
MARK = "<!-- generated by scripts/summarise.py: {} -->"
END = "<!-- end of generated table -->"


def forecast_table(ev) -> str:
    fc = ev["forecast"]
    lines = ["| RMSE (mg/dL) | 30 min | 60 min | 120 min |", "| --- | --- | --- | --- |"]
    for key, name in FORECAST_ROWS:
        cells = [f1(fc[f"{h} min"][key]["rmse_mg_dl"]) for h in (30, 60, 120)]
        if key == "C":
            cells = [f"**{c}**" for c in cells]
            cells[2] += f" ({interval(fc['120 min']['C']['rmse_95ci'])})"
            name = f"**{name}**"
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def alert_table(ev) -> str:
    b05, b10 = ev["alarms"]["budget_0.5"], ev["alarms"]["budget_1.0"]
    lines = ["| Alert score (thresholds set on training patients) | Lows caught, budget 0.5 a day | Alerts a day on held-out patients | False alerts a day | Alert precision | Lows caught, budget 1.0 a day |",
             "| --- | --- | --- | --- | --- | --- |"]
    for key, name in ALERT_ROWS:
        a, c = b05[key], b10[key]
        row = [f"{a['caught']} of {a['eligible_events']}", f"{a['emitted_alerts_per_day']:.2f}", f"{a['false_alerts_per_day']:.2f}",
               f"{a['alert_precision_percent']:.0f}%", f"{c['caught']} of {c['eligible_events']}"]
        if key == "current":
            name, row = f"**{name}**", [f"**{row[0]}**"] + row[1:]
        lines.append(f"| {name} | " + " | ".join(row) + " |")
    return "\n".join(lines)


def write_readme_tables(ev, readme=ROOT / "README.md") -> None:
    """Replace the README's generated result tables, between their markers."""
    text = readme.read_text(encoding="utf-8")
    for name, table in (("forecast table", forecast_table(ev)), ("alert table", alert_table(ev))):
        start = text.index(MARK.format(name)) + len(MARK.format(name))
        end = text.index(END, start)
        text = text[:start] + "\n" + table + "\n" + text[end:]
    readme.write_text(text, encoding="utf-8")


